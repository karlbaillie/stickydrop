const { contextBridge, ipcRenderer } = require('electron');
contextBridge.exposeInMainWorld('api', {
  load: () => ipcRenderer.invoke('load'),
  saveNotes: (n) => ipcRenderer.send('save-notes', n),
  saveBoard: (b) => ipcRenderer.send('save-board', b),
  setSettings: (p) => ipcRenderer.invoke('set-settings', p),
  resetSettings: () => ipcRenderer.invoke('reset-settings'),
  resizeHeight: (px, commit) => ipcRenderer.invoke('resize-height', px, commit),
  setPinned: (v) => ipcRenderer.send('pinned', v),
  hide: () => ipcRenderer.send('hide'),
  quit: () => ipcRenderer.send('quit'),
  onShow: (cb) => ipcRenderer.on('show', cb),
  onFocusNote: (cb) => ipcRenderer.on('focus-note', (_e, id) => cb(id)),
  onDataChanged: (cb) => ipcRenderer.on('data-changed', (_e, d) => cb(d)),
  saveAttachment: (bytes, type) => ipcRenderer.invoke('save-attachment', bytes, type),
  openAttachment: (name) => ipcRenderer.send('open-attachment', name),
  noteMenu: (note, tabs) => ipcRenderer.invoke('note-menu', note, tabs),
  exportMarkdown: () => ipcRenderer.invoke('export-markdown'),
  exportBackup: () => ipcRenderer.invoke('export-backup'),
  importMarkdown: () => ipcRenderer.invoke('import-markdown'),
  restoreBackup: () => ipcRenderer.invoke('restore-backup'),
  dataInfo: () => ipcRenderer.invoke('data-info'),
  openDataFolder: () => ipcRenderer.send('open-data-folder'),
  chooseSyncDir: () => ipcRenderer.invoke('choose-sync-dir'),
  setSyncDir: (dir, mode) => ipcRenderer.invoke('set-sync-dir', dir, mode),
  stopSync: () => ipcRenderer.invoke('stop-sync'),
});
